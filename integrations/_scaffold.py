#!/usr/bin/env python3
"""
_scaffold.py -- keeps the DEMEX connector layer consistent.

Run it any time you add or edit a connector:

    python integrations/_scaffold.py

What it does, idempotently:
  1. Walks every folder in integrations/ that holds a connector.json.
  2. Creates the four standard subfolders (inbound, outbound, logs, samples)
     if they are missing.
  3. Validates each connector.json against the demex_connector/v1 shape and
     prints anything that is wrong or suspicious.
  4. Regenerates integrations/registry.json from the connector.json files, so
     the registry can never drift from the folders.

It never overwrites a connector.json or a README you have edited.
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter
from datetime import date

ROOT = os.path.dirname(os.path.abspath(__file__))
SUBS = ("inbound", "outbound", "logs", "samples")

REQUIRED = (
    "schema", "key", "name", "vendor", "category", "status", "direction",
    "purpose", "auth", "access", "entities", "demex_mapping", "code",
    "trigger", "known_limits", "owner_action_required", "last_verified",
)

VALID_STATUS = {"live", "partial", "planned", "unverified", "blocked"}
VALID_DIRECTION = {"inbound", "outbound", "bidirectional", "unknown"}


def connector_dirs() -> list[str]:
    out = []
    for name in sorted(os.listdir(ROOT)):
        d = os.path.join(ROOT, name)
        if os.path.isdir(d) and os.path.exists(os.path.join(d, "connector.json")):
            out.append(d)
    return out


def validate(spec: dict, key_from_folder: str) -> list[str]:
    problems = []
    for field in REQUIRED:
        if field not in spec:
            problems.append(f"missing required field '{field}'")
    if spec.get("schema") != "demex_connector/v1":
        problems.append(f"schema is {spec.get('schema')!r}, expected 'demex_connector/v1'")
    if spec.get("key") != key_from_folder:
        problems.append(f"key {spec.get('key')!r} does not match folder name {key_from_folder!r}")
    if spec.get("status") not in VALID_STATUS:
        problems.append(f"status {spec.get('status')!r} not one of {sorted(VALID_STATUS)}")
    if spec.get("direction") not in VALID_DIRECTION:
        problems.append(f"direction {spec.get('direction')!r} not one of {sorted(VALID_DIRECTION)}")
    if spec.get("status") in {"live", "partial"} and not spec.get("code"):
        problems.append("status is live/partial but no code file is listed - either wire it or downgrade the status")
    if not spec.get("known_limits"):
        problems.append("known_limits is empty - an unstated limit becomes a wrong bid")
    for secret in (spec.get("auth") or {}).get("secrets", []):
        if any(ch in secret for ch in " ='\""):
            problems.append(f"auth.secrets should hold env var NAMES, not values (saw {secret!r})")
    return problems


def main() -> int:
    dirs = connector_dirs()
    if not dirs:
        print("no connectors found under", ROOT)
        return 1

    registry = {
        "schema": "demex_integration_registry/v1",
        "generated": date.today().isoformat(),
        "note": "Generated by integrations/_scaffold.py from each connector.json. Do not hand-edit.",
        "counts": {},
        "connectors": [],
    }
    counts: Counter[str] = Counter()
    failures = 0

    for d in dirs:
        folder = os.path.basename(d)
        if folder.startswith("_"):
            continue
        spec = json.load(open(os.path.join(d, "connector.json"), encoding="utf-8"))

        for sub in SUBS:
            p = os.path.join(d, sub)
            os.makedirs(p, exist_ok=True)
            keep = os.path.join(p, ".gitkeep")
            if not os.listdir(p):
                open(keep, "w", encoding="utf-8").close()

        problems = validate(spec, folder)
        if problems:
            failures += 1
            print(f"\n[!] {folder}")
            for p in problems:
                print(f"    - {p}")

        counts[spec.get("status", "?")] += 1
        registry["connectors"].append({
            "key": spec.get("key"),
            "name": spec.get("name"),
            "vendor": spec.get("vendor"),
            "category": spec.get("category"),
            "status": spec.get("status"),
            "direction": spec.get("direction"),
            "last_verified": spec.get("last_verified"),
            "path": f"integrations/{folder}/",
        })

    registry["counts"] = dict(sorted(counts.items()))
    json.dump(registry, open(os.path.join(ROOT, "registry.json"), "w", encoding="utf-8"), indent=2)

    print(f"\n{len(registry['connectors'])} connectors -> registry.json  {dict(sorted(counts.items()))}")
    if failures:
        print(f"{failures} connector(s) have problems above.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
